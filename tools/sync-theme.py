"""Generate the native color constants from one reviewed palette."""
import argparse
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
theme = json.loads((root / 'shared/theme.json').read_text(encoding='utf-8'))
colors = theme['colors']
assert all(re.fullmatch(r'#[0-9A-F]{6}', value) for value in colors.values())
overrides = theme.get('platformOverrides', {})
for platform, values in overrides.items():
    assert platform in {'android', 'harmony'}, f'Unknown theme platform: {platform}'
    assert set(values) <= set(colors), f'Unknown color override for {platform}'
    assert all(re.fullmatch(r'#[0-9A-F]{6}', value) for value in values.values())
android_colors = colors | overrides.get('android', {})
harmony_colors = colors | overrides.get('harmony', {})
names = {'forest': 'Forest', 'heroAccent': 'HeroAccent', 'heroLine': 'HeroLine', 'sage': 'Sage', 'sageBorder': 'SageBorder', 'background': 'Cream', 'card': 'Card',
         'field': 'Field', 'ink': 'Ink', 'muted': 'Muted', 'outline': 'Outline', 'onForest': 'OnForest',
         'onForestMuted': 'OnForestMuted', 'expense': 'ExpenseColor', 'income': 'IncomeColor',
         'refund': 'RefundColor', 'error': 'ErrorColor'}
kotlin = '// Generated by tools/sync-theme.py from shared/theme.json.\npackage com.yiyu.ledger.ui\n\nimport androidx.compose.ui.graphics.Color\n\n'
kotlin += ''.join(f'val {names[key]} = Color(0xFF{value[1:]})\n' for key, value in android_colors.items())
typescript = '// Generated by tools/sync-theme.py from shared/theme.json.\nexport interface LedgerPalette {\n'
typescript += ''.join(f'  {key}: string;\n' for key in colors)
typescript += '}\nexport const PALETTE: LedgerPalette = {\n'
typescript += ',\n'.join(f"  {key}: '{value}'" for key, value in harmony_colors.items()) + '\n};\n'
outputs = {
    'android': (root / 'android/app/src/main/java/com/yiyu/ledger/ui/Palette.kt', kotlin),
    'harmony': (root / 'harmony/entry/src/main/ets/model/Palette.ts', typescript),
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
parser.add_argument('--platform', choices=['all', 'android', 'harmony'], default='all')
args = parser.parse_args()
for platform, (path, text) in outputs.items():
    if args.platform != 'all' and platform != args.platform:
        continue
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            raise SystemExit(f'Palette needs regeneration: {path}')
    else:
        path.write_text(text, encoding='utf-8', newline='\n')
print('Native palettes match shared theme and platform overrides' if args.check else f'Updated {args.platform} native palette(s)')
