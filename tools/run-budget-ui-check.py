"""Verify budget, swipe and actual rendered styles on disposable Android 15/16 emulators."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import tarfile
import time
import xml.etree.ElementTree as ET
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ADB = Path('D:/Android/Sdk/platform-tools/adb.exe')
SERIAL = 'emulator-5554'
REPORT = ROOT / 'artifacts/android-0.6.1-ui'
PROFILES = [('standard', 393, 873, 1.0), ('narrow', 320, 720, 1.0), ('large_font', 360, 800, 2.0)]


def adb(*args, timeout=60):
    result = subprocess.run([str(ADB), '-s', SERIAL, *args], capture_output=True, timeout=timeout, check=True)
    return result.stdout.decode('utf-8', errors='replace').strip()


def main():
    global SERIAL, REPORT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--api', type=int, required=True, choices=[35, 36])
    parser.add_argument('--serial', default='emulator-5554')
    parser.add_argument('--profiles', default=','.join(p[0] for p in PROFILES))
    args = parser.parse_args()
    selected = args.profiles.split(',')
    if any(p not in {x[0] for x in PROFILES} for p in selected): parser.error('Unknown screen profile')
    SERIAL = args.serial
    REPORT = REPORT / f'api{args.api}'
    if not re.fullmatch(r'emulator-\d+', SERIAL) or not adb('emu', 'avd', 'name').startswith(f'Yiyu_API{args.api}'):
        raise RuntimeError('Tests are restricted to the matching disposable Yiyu development emulator')
    if adb('shell', 'getprop', 'ro.build.version.sdk') != str(args.api): raise RuntimeError('Incorrect Android API')
    apk_hash = hashlib.sha256((ROOT / 'android/app/build/outputs/apk/debug/app-debug.apk').read_bytes()).hexdigest()
    installed = adb('shell', 'pm', 'path', 'com.yiyu.ledger').removeprefix('package:')
    if adb('shell', 'sha256sum', installed).split()[0].lower() != apk_hash:
        raise RuntimeError('Install the current build before checking its UI')
    REPORT.mkdir(parents=True, exist_ok=True)
    original_size = adb('shell', 'wm', 'size')
    original_density = adb('shell', 'wm', 'density')
    original_font = adb('shell', 'settings', 'get', 'system', 'font_scale')
    original_rotation = adb('shell', 'settings', 'get', 'system', 'user_rotation')
    original_accelerometer = adb('shell', 'settings', 'get', 'system', 'accelerometer_rotation')
    original_fixed = adb('shell', 'cmd', 'window', 'fixed-to-user-rotation')
    # A focused rerun may retain completed profiles only for this exact APK/API.
    previous = REPORT / 'results.json'
    recorded = {}
    if previous.exists():
        report = json.loads(previous.read_text(encoding='utf-8'))
        if report.get('api') == args.api and report.get('apk_sha256') == apk_hash:
            recorded = {p['profile']: p for p in report.get('profiles', [])}
    results = []
    try:
        adb('shell', 'cmd', 'window', 'fixed-to-user-rotation', 'enabled')
        adb('shell', 'settings', 'put', 'system', 'accelerometer_rotation', '0')
        adb('shell', 'settings', 'put', 'system', 'user_rotation', '0')
        adb('shell', 'cmd', 'window', 'user-rotation', 'lock', '0')
        for name, width, height, font in PROFILES:
            if name not in selected: continue
            print(f'{name}: {width}x{height}dp, font {font}', flush=True)
            adb('shell', 'am', 'force-stop', 'com.yiyu.ledger')
            adb('shell', 'wm', 'size', f'{width*2}x{height*2}')
            adb('shell', 'wm', 'density', '320')
            adb('shell', 'settings', 'put', 'system', 'font_scale', str(font))
            time.sleep(2)
            output = adb('shell', 'am', 'instrument', '-w', '-e', 'class', 'com.yiyu.ledger.BudgetAndSwipeUiTest',
                         'com.yiyu.ledger.test/androidx.test.runner.AndroidJUnitRunner', timeout=240)
            (REPORT / f'{name}.log').write_text(output, encoding='utf-8')
            archive = REPORT / f'{name}.tar'
            archive.write_bytes(subprocess.check_output([str(ADB), '-s', SERIAL, 'exec-out', 'run-as', 'com.yiyu.ledger', 'tar', '-cf', '-', '-C', 'files/budget-swipe', '.']))
            folder = REPORT / name
            folder.mkdir(exist_ok=True)
            # This directory contains only synthetic emulator screenshots generated by this tool.
            for old in folder.iterdir():
                if old.is_file() and old.suffix in ('.png', '.xml', '.txt'): old.unlink()
            with tarfile.open(archive) as images: images.extractall(folder, filter='data')
            archive.unlink()
            expected = {'unset.png', 'available.png', 'reached.png', 'over-budget.png', 'multiple-laps.png', 'swipe-reveal.png',
                        'deleted-budget-refreshed.png', 'budget-keyboard.png', 'two-column-extreme.png', 'extreme-amount.png'}
            present = {p.name for p in folder.glob('*.png')}
            dimensions = all(struct.unpack_from('>II', (folder / p).read_bytes(), 16) == (width*2, height*2) for p in expected & present)
            passed = bool(re.search(r'OK \(2 tests\)', output)) and expected <= present and dimensions and 'FAILURES' not in output
            styles = check_rendered_styles(folder) if passed else {'passed': False, 'reason': 'UI tests/captures incomplete'}
            passed = passed and styles['passed']
            results.append(dict(profile=name, width_dp=width, height_dp=height, font_scale=font, passed=passed,
                tested_at=datetime.now(timezone.utc).isoformat(), screenshot_dimensions_verified=dimensions, styles=styles))
            recorded[name] = results[-1]
            complete = [recorded[p[0]] for p in PROFILES if p[0] in recorded]
            (REPORT / 'results.json').write_text(json.dumps(dict(api=args.api, apk_sha256=apk_hash, profiles=complete), indent=2), encoding='utf-8')
            print(f'{name}: {"PASS" if passed else "FAIL"}', flush=True)
            if not passed:
                print(output[-5000:], flush=True)
                print(json.dumps(styles), flush=True)
                break
    finally:
        size = re.search(r'Override size: (\d+x\d+)', original_size)
        density = re.search(r'Override density: (\d+)', original_density)
        adb('shell', 'wm', 'size', size.group(1) if size else 'reset')
        adb('shell', 'wm', 'density', density.group(1) if density else 'reset')
        if original_font == 'null': adb('shell', 'settings', 'delete', 'system', 'font_scale')
        else: adb('shell', 'settings', 'put', 'system', 'font_scale', original_font)
        adb('shell', 'cmd', 'window', 'user-rotation', 'free' if original_accelerometer == '1' else 'lock', original_rotation if original_rotation != 'null' else '0')
        adb('shell', 'cmd', 'window', 'fixed-to-user-rotation', original_fixed)
        for key, value in [('user_rotation', original_rotation), ('accelerometer_rotation', original_accelerometer)]:
            adb('shell', 'settings', 'delete' if value == 'null' else 'put', 'system', key, *([] if value == 'null' else [value]))
    if len(results) != len(selected) or not all(r['passed'] for r in results): raise SystemExit(1)


def check_rendered_styles(folder):
    """Use the captured pixels rather than trusting the declared Compose dimensions."""
    def bounds(capture, node_id):
        nodes = ET.parse(folder / f'{capture}.xml').getroot().iter('node')
        raw = next(node.attrib['bounds'] for node in nodes if node.attrib.get('resource-id') == node_id)
        return tuple(map(int, re.findall(r'\d+', raw)))

    red, green, sage, page, card = (173, 89, 76), (71, 107, 83), (225, 235, 211), (245, 245, 239), (254, 254, 250)
    checks = {}
    try:
        image = Image.open(folder / 'swipe-reveal.png').convert('RGB')
        left, top, right, bottom = bounds('swipe-reveal', 'swipe_delete_budget_ui_expense')
        corners = [image.getpixel((x, y)) for x in (left+4, right-5) for y in (top+4, bottom-5)]
        checks['rectangular_delete'] = all(pixel == red for pixel in corners)
        a, b, c, d = bounds('swipe-reveal', 'swipe_gap_budget_ui_expense')
        checks['gap_16dp'] = c-a == 32 and image.getpixel(((a+c)//2, (b+d)//2)) == page
        thickness = {}
        for capture in ('unset', 'available', 'reached', 'over-budget', 'multiple-laps', 'extreme-amount', 'deleted-budget-refreshed'):
            image = Image.open(folder / f'{capture}.png').convert('RGB')
            a, b, c, d = bounds(capture, 'monthly_budget_ring')
            assert c-a == 416 and d-b == 416, f'{capture} needs a full 208dp ring'
            pixels = [image.getpixel(((a+c)//2, y)) in (red, green, sage) for y in range(b, b+(d-b)//3)]
            runs = re.findall('1+', ''.join('1' if p else '0' for p in pixels))
            thickness[capture] = max(map(len, runs), default=0)
        checks['stroke_pixels'] = thickness
        checks['stroke_22dp'] = all(42 <= length <= 46 for length in thickness.values())
        a, b, c, d = bounds('two-column-extreme', 'stats_summary_card')
        image = Image.open(folder / 'two-column-extreme.png').convert('RGB')
        checks['warm_summary_card'] = image.getpixel((a+28, b+24)) == card
        a, b, c, d = bounds('unset', 'monthly_budget_card')
        image = Image.open(folder / 'unset.png').convert('RGB')
        checks['matching_budget_card'] = image.getpixel((a+28, b+24)) == card
        checks['passed'] = all(value for key, value in checks.items() if key != 'stroke_pixels')
    except (StopIteration, AssertionError, ValueError, IndexError) as error:
        checks.update(passed=False, reason=str(error))
    return checks


if __name__ == '__main__': main()
